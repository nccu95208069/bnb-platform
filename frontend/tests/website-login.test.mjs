const origin='https://os.example.invalid';
function request(path,body,cookie){return new NextRequest(origin+path,{method:'POST',headers:{origin,'content-type':'application/json',...(cookie?{cookie}:{})},body:JSON.stringify(body)});}
function patch(t,store){for(const target of [websiteStore,customerStore])for(const key of ['read','commit','limit'])t.mock.method(target,key,store[key].bind(store));}
test('website login challenge is tied to intended connection and browser, with safe fixed return URL',async t=>{
 const f=await websiteFixture({approve:false});patch(t,f.store);const proof=newLoginProof(),requestKey=randomUUID();let sent,sendCount=0;
 const input={email:f.account.email,requestKey,proof,websiteConnectionId:f.connection.connectionId};
 const send=async(_to,_subject,text)=>{sent=text;sendCount++;return 'synthetic-mail-id';};
 assert.equal((await requestEmailLogin(f.store,input,send)).status,'accepted');await requestEmailLogin(f.store,input,send);assert.equal(sendCount,1);
 const token=sent.match(/\/signin#([^\s]+)/)[1];
 await assert.rejects(consumeEmailLogin(f.store,token,proof),/LINK_INVALID/);
 await assert.rejects(consumeEmailLogin(f.store,token,proof,undefined,undefined,randomUUID()),/LINK_INVALID/);
 await assert.rejects(requestEmailLogin(f.store,{...input,websiteConnectionId:randomUUID()},send),/IDEMPOTENCY_CONFLICT/);
 const response=await Login.POST(request('/api/customer-login',{action:'consume',token},`${LOGIN_PROOF_COOKIE}=${proof}; ${WEBSITE_LOGIN_COOKIE}=${f.connection.connectionId}`));
 assert.equal(response.status,200,await response.clone().text());assert.equal((await response.json()).url,'/website-booking?connection='+f.connection.connectionId);
 assert.equal([...f.store.values.keys()].filter(k=>k.startsWith('workspace:')).length,0);
});
test('an unregistered owner can verify email during a pending site request and create their own sales-off calendar',async()=>{
 const f=await websiteFixture({approve:false});
 const studio={...f.client,id:'self-service-studio',site_ids:[],allow_new_sites:true};
 const siteId=randomUUID();
 const pending=await prepareConnection(f.store,studio,{...f.prepare,requestId:randomUUID(),siteId},f.now);
 f.store.values.delete(accountKey(f.account.email));
 assert.equal((await f.store.read(accountKey(f.account.email))).value,null);
 const proof=newLoginProof();let sent;
 const input={email:f.account.email,requestKey:randomUUID(),proof,websiteConnectionId:pending.connectionId};
 assert.equal((await requestEmailLogin(f.store,input,async(_to,_subject,body)=>{sent=body;return 'synthetic-mail-id';})).status,'accepted');
 const token=sent.match(/\/signin#([^\s]+)/)[1];
 const result=await consumeEmailLogin(f.store,token,proof,undefined,undefined,pending.connectionId);
 assert.notEqual(result.account.id,f.account.id);
 assert(result.account.emailVerifiedAt);
 assert.deepEqual(result.account.workspaces,[]);
 const review=await ownerConnection(f.store,result.account,pending.connectionId,f.now);
 assert.equal(review.connection.state,'awaiting_owner');
 assert.equal(review.connection.requiresSiteApproval,true);
 assert.equal((await approveConnection(f.store,result.account,{...f.approval,connectionId:pending.connectionId},f.now)).state,'connected');
 const account=(await f.store.read(accountKey(f.account.email))).value;
 assert.equal(account.workspaces.length,1);
 const status=await connectionStatus(f.store,studio,{schemaVersion:1,action:'status',siteId,connectionId:pending.connectionId},f.now);
 const binding=(await f.store.read('website:binding:'+status.bindingId)).value;
 assert.equal(binding.ownerAccountId,result.account.id);
 assert.equal(binding.siteId,siteId);
 assert.equal(binding.enabled,false);
 assert.equal(status.salesEnabled,false);
 assert.deepEqual((await f.store.read(studioSitesKey(studio.id))).value,[siteId]);
 const secondSiteId=randomUUID();
 const second=await prepareConnection(f.store,studio,{...f.prepare,requestId:randomUUID(),siteId:secondSiteId},f.now);
 await approveConnection(f.store,result.account,{...f.approval,connectionId:second.connectionId,requestKey:randomUUID(),slug:'synthetic-second'},f.now);
 const secondStatus=await connectionStatus(f.store,studio,{schemaVersion:1,action:'status',siteId:secondSiteId,connectionId:second.connectionId},f.now);
 const secondBinding=(await f.store.read('website:binding:'+secondStatus.bindingId)).value;
 assert.notEqual(secondBinding.workspaceId,binding.workspaceId);
 assert.equal(secondStatus.salesEnabled,false);
 assert.deepEqual((await f.store.read(studioSitesKey(studio.id))).value,[siteId,secondSiteId]);
});

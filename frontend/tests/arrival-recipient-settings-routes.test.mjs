import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createHash } from 'node:crypto';
import { NextRequest } from 'next/server';
import { fixture } from './helpers/calendar-fixture.mjs';
import { RedisCustomerStore } from '../src/lib/customer-workspaces/store.ts';
import { accountKey, CUSTOMER_COOKIE, sessionFor } from '../src/lib/customer-workspaces/auth.ts';
import { newPasswordlessCredential } from '../src/lib/customer-workspaces/identity.ts';
import { GET, POST } from '../src/app/api/arrival-reminders/settings/route.ts';
import { POST as workerPost } from '../src/app/api/integration/arrival-reminders/v1/route.ts';

test('owner-only settings route and selected steward-only LINE pairing route enforce session and origin', async t => {
  process.env.CUSTOMER_WORKSPACES_ENABLED = 'true';
  process.env.CUSTOMER_SESSION_SECRET = 'synthetic-arrival-recipient-route-secret-32';
  const f = fixture();
  const owner = { id: randomUUID(), email: 'owner@example.test', credential: newPasswordlessCredential(), workspaces: [] };
  const steward = { id: randomUUID(), email: 'steward@example.test', credential: newPasswordlessCredential(), workspaces: [] };
  f.workspace.members[0].accountId = owner.id;
  f.workspace.members.push({ accountId: steward.id, email: steward.email, role: 'housekeeper', active: true, allProperties: true, propertyIds: [] });
  await f.put(f.workspace);
  f.store.data.set(accountKey(owner.email), JSON.stringify(owner));
  f.store.data.set(accountKey(steward.email), JSON.stringify(steward));
  t.mock.method(RedisCustomerStore.prototype, 'read', function(key) { return f.store.read(key); });
  t.mock.method(RedisCustomerStore.prototype, 'commit', function(changes) { return f.store.commit(changes); });
  t.mock.method(RedisCustomerStore.prototype, 'limit', async function() {});
  const url = `https://app.test/api/arrival-reminders/settings?workspace=${f.workspace.slug}&property=property`;
  const req = (account, input, origin = 'https://app.test') => new NextRequest(url, { method: input ? 'POST' : 'GET', headers: { ...(account ? { cookie: `${CUSTOMER_COOKIE}=${sessionFor(account)}` } : {}), ...(input ? { origin, 'content-type': 'application/json' } : {}) }, ...(input ? { body: JSON.stringify(input) } : {}) });
  assert.equal((await GET(req(null))).status, 401);
  assert.equal((await GET(req(owner))).status, 200);
  const input = { action: 'save', recipientAccountIds: [steward.id], enabled: true, includeUnconfirmed: false };
  assert.equal((await POST(req(owner, input, 'https://evil.test'))).status, 403);
  assert.equal((await POST(req(steward, input))).status, 403);
  assert.equal((await POST(req(owner, input))).status, 200);
  assert.equal((await POST(req(owner, { action: 'pair' }))).status, 403);
  const paired = await POST(req(steward, { action: 'pair' }));
  assert.equal(paired.status, 200);
  const command = (await paired.json()).command;
  assert.match(command, /^接收入住 /);
  const limited = await GET(req(steward)); assert.equal(limited.status, 200);
  assert.deepEqual((await limited.json()).members, []);
  process.env.ARRIVAL_REMINDERS_ENABLED = 'true';
  const token = 'synthetic-arrival-worker-token-long-enough';
  process.env.ARRIVAL_REMINDER_WORKERS = JSON.stringify([{ id: 'line-worker', token_sha256: createHash('sha256').update(token).digest('hex'), targets: [{ id: 'legacy-test', kind: 'legacy', propertyId: 'sweetfun', recipientId: 'U' + 'a'.repeat(32), verifiedAt: '2026-01-01T00:00:00Z', verifiedBy: 'synthetic' }] }]);
  const pairUrl = 'https://app.test/api/integration/arrival-reminders/v1';
  const pairReq = (extra = {}, recipientId = 'U' + 'b'.repeat(32)) => new NextRequest(pairUrl, { method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json', ...extra }, body: JSON.stringify({ action: 'pair', pairingToken: command.split(' ')[1], recipientId }) });
  assert.equal((await workerPost(pairReq({ cookie: 'fake=1' }))).status, 403);
  assert.equal((await workerPost(pairReq({ origin: 'https://app.test' }))).status, 403);
  assert.equal((await workerPost(pairReq())).status, 200);
  assert.equal((await GET(req(steward))).status, 200);
  assert.equal((await (await GET(req(steward))).json()).recipients[0].lineConnected, true);
  assert.equal((await workerPost(pairReq({}, 'U' + 'c'.repeat(32)))).status, 409);
});
